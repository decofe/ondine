/** @module Compiles the video's Mermaid sources with `ondine/compiler` into `src/diagrams.generated.ts`. */
import * as Fs from 'node:fs'
import * as Path from 'node:path'
import { render } from 'ondine/compiler'
import { sources } from '../src/Sources.ts'

const svgs = Object.fromEntries(
  Object.entries(sources).map(([name, source]) => [
    name,
    render(source, { autoDirection: false, idPrefix: `${name}-` }).svg,
  ]),
)

Fs.writeFileSync(
  Path.join(import.meta.dirname, '../src/diagrams.generated.ts'),
  `// Generated by scripts/diagrams.ts. Do not edit.\nexport const svgs = ${JSON.stringify(svgs, null, 2)} as const\n`,
)
console.log(`Compiled ${Object.keys(svgs).length} diagrams to src/diagrams.generated.ts`)
