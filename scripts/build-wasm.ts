/**
 * Builds one WebAssembly module per diagram type and inlines each as base64 in
 * `src/internal/<type>.generated.ts`. Outputs are gitignored and rewritten only when they change.
 * @module
 */
import * as ChildProcess from 'node:child_process'
import * as Fs from 'node:fs'
import * as Path from 'node:path'

const root = Path.resolve(import.meta.dirname, '..')

/** Diagram types with a compiler module. Each builds into its own WebAssembly module. */
const types = ['flowchart'] as const

for (const type of types)
  write(Path.join(root, `src/internal/${type}.generated.ts`), source(build(type)))

/** Builds the `wasm` crate with one diagram feature, optimizes it, and returns its bytes. */
function build(feature: string): Buffer {
  const targetDir = `target/wasm-${feature}`

  ChildProcess.execFileSync(
    'cargo',
    [
      'build',
      '--package',
      'wasm',
      '--no-default-features',
      '--features',
      feature,
      '--profile',
      'wasm',
      '--target',
      'wasm32-unknown-unknown',
      '--target-dir',
      targetDir,
    ],
    { cwd: root, stdio: 'inherit' },
  )

  const input = Path.join(root, targetDir, 'wasm32-unknown-unknown/wasm/wasm.wasm')
  const output = Path.join(root, targetDir, 'optimized.wasm')

  // Rust's wasm32 target enables these proposals by default, so the optimizer must accept them.
  const proposals = [
    '--enable-bulk-memory',
    '--enable-multivalue',
    '--enable-mutable-globals',
    '--enable-nontrapping-float-to-int',
    '--enable-reference-types',
    '--enable-sign-ext',
  ]

  // The pinned npm build of Binaryen keeps output identical across machines.
  ChildProcess.execFileSync(
    Path.join(root, 'node_modules/.bin/wasm-opt'),
    ['-Oz', ...proposals, '--strip-debug', '--strip-producers', input, '-o', output],
    { cwd: root, stdio: 'inherit' },
  )

  return Fs.readFileSync(output)
}

/** The generated module that inlines `bytes`. */
function source(bytes: Buffer): string {
  return `// Generated by scripts/build-wasm.ts. Do not edit.\nexport const wasm = '${bytes.toString('base64')}'\n`
}

/** Writes a file only when its contents change, so watchers skip unchanged outputs. */
function write(file: string, contents: string): void {
  if (Fs.existsSync(file) && Fs.readFileSync(file, 'utf8') === contents) return

  Fs.mkdirSync(Path.dirname(file), { recursive: true })
  Fs.writeFileSync(file, contents)
}
